-- 15. TABLA: transferencia_inventario
 

CREATE TABLE transferencia_inventario (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tanque_origen_id UUID NOT NULL,
    tanque_destino_id UUID NOT NULL,
    registrada_por_usuario_id UUID NOT NULL,
    cantidad NUMERIC(12,2) NOT NULL,
