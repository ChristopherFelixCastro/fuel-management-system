        ON DELETE RESTRICT,

    CONSTRAINT chk_transferencia_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_transferencia_tanques_distintos
        CHECK (tanque_origen_id <> tanque_destino_id)
);

 
-- 16. TABLA: ajuste_inventario
 

CREATE TABLE ajuste_inventario (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tanque_id UUID NOT NULL,
    reportado_por_usuario_id UUID NOT NULL,
    revisado_por_usuario_id UUID,
    tipo_ajuste VARCHAR(20) NOT NULL,
    cantidad NUMERIC(12,2) NOT NULL,
    motivo VARCHAR(300) NOT NULL,
    estado VARCHAR(25) NOT NULL DEFAULT 'PENDIENTE',
    fecha_reporte TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_revision TIMESTAMPTZ,
    motivo_rechazo VARCHAR(300),
    observaciones VARCHAR(500),

    CONSTRAINT fk_ajuste_tanque
        FOREIGN KEY (tanque_id)
        REFERENCES tanque(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ajuste_reportado_por
        FOREIGN KEY (reportado_por_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_ajuste_revisado_por
        FOREIGN KEY (revisado_por_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_ajuste_tipo
        CHECK (
            tipo_ajuste IN (
                'POSITIVO',
                'NEGATIVO'
            )
        ),

    CONSTRAINT chk_ajuste_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_ajuste_estado
        CHECK (
            estado IN (
                'PENDIENTE',
                'APROBADO',
                'RECHAZADO'
            )
        ),

    CONSTRAINT chk_ajuste_revision
        CHECK (
            estado = 'PENDIENTE'
            OR (
                revisado_por_usuario_id IS NOT NULL
                AND fecha_revision IS NOT NULL
            )
        ),

    CONSTRAINT chk_ajuste_rechazo
        CHECK (
            estado <> 'RECHAZADO'
            OR motivo_rechazo IS NOT NULL
        )
);

 
-- 17. TABLA: movimiento_inventario
 

CREATE TABLE movimiento_inventario (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tanque_id UUID NOT NULL,
    registrado_por_usuario_id UUID NOT NULL,
    tipo_movimiento VARCHAR(30) NOT NULL,
    cantidad NUMERIC(12,2) NOT NULL,
    saldo_anterior NUMERIC(12,2) NOT NULL,
    saldo_posterior NUMERIC(12,2) NOT NULL,
    recepcion_id UUID,
    despacho_id UUID,
    transferencia_id UUID,
    ajuste_id UUID,
    fecha_movimiento TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    observaciones VARCHAR(500),

    CONSTRAINT fk_movimiento_tanque
        FOREIGN KEY (tanque_id)
        REFERENCES tanque(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimiento_usuario
        FOREIGN KEY (registrado_por_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimiento_recepcion
        FOREIGN KEY (recepcion_id)
        REFERENCES recepcion_combustible(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimiento_despacho
        FOREIGN KEY (despacho_id)
        REFERENCES despacho(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimiento_transferencia
        FOREIGN KEY (transferencia_id)
        REFERENCES transferencia_inventario(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_movimiento_ajuste
        FOREIGN KEY (ajuste_id)
        REFERENCES ajuste_inventario(id)
        ON DELETE RESTRICT,

    CONSTRAINT uq_movimiento_recepcion
        UNIQUE (recepcion_id),

    CONSTRAINT uq_movimiento_despacho
        UNIQUE (despacho_id),

    CONSTRAINT uq_movimiento_ajuste
        UNIQUE (ajuste_id),

    CONSTRAINT chk_movimiento_tipo
        CHECK (
            tipo_movimiento IN (
                'RECEPCION',
                'DESPACHO',
                'TRANSFERENCIA_ENTRADA',
                'TRANSFERENCIA_SALIDA',
                'MERMA',
                'AJUSTE_POSITIVO',
                'AJUSTE_NEGATIVO'
            )
        ),

    CONSTRAINT chk_movimiento_cantidad
        CHECK (cantidad > 0),

    CONSTRAINT chk_movimiento_saldo_anterior
        CHECK (saldo_anterior >= 0),

    CONSTRAINT chk_movimiento_saldo_posterior
        CHECK (saldo_posterior >= 0),

    CONSTRAINT chk_movimiento_origen
        CHECK (
            (
                tipo_movimiento = 'RECEPCION'
                AND recepcion_id IS NOT NULL
                AND despacho_id IS NULL
                AND transferencia_id IS NULL
                AND ajuste_id IS NULL
            )
            OR
            (
                tipo_movimiento = 'DESPACHO'
                AND recepcion_id IS NULL
                AND despacho_id IS NOT NULL
                AND transferencia_id IS NULL
                AND ajuste_id IS NULL
            )
            OR
            (
                tipo_movimiento IN (
                    'TRANSFERENCIA_ENTRADA',
                    'TRANSFERENCIA_SALIDA'
                )
                AND recepcion_id IS NULL
                AND despacho_id IS NULL
                AND transferencia_id IS NOT NULL
                AND ajuste_id IS NULL
            )
            OR
            (
                tipo_movimiento IN (
                    'AJUSTE_POSITIVO',
                    'AJUSTE_NEGATIVO'
                )
                AND recepcion_id IS NULL
                AND despacho_id IS NULL
                AND transferencia_id IS NULL
                AND ajuste_id IS NOT NULL
            )
            OR
            (
                tipo_movimiento = 'MERMA'
                AND recepcion_id IS NULL
                AND despacho_id IS NULL
                AND transferencia_id IS NULL
                AND ajuste_id IS NULL
            )
        )
);




 
-- 18. TABLA: cierre_diario
 

CREATE TABLE cierre_diario (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    tanque_id UUID NOT NULL,
    creado_por_usuario_id UUID NOT NULL,
    revisado_por_usuario_id UUID,
    fecha_cierre DATE NOT NULL,

    stock_inicial NUMERIC(12,2) NOT NULL,
    total_recepciones NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_transferencias_entrada NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_transferencias_salida NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_despachos NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_ajustes_positivos NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_ajustes_negativos NUMERIC(12,2) NOT NULL DEFAULT 0,

    stock_teorico_final NUMERIC(12,2) NOT NULL,
    stock_fisico_final NUMERIC(12,2) NOT NULL,
    diferencia NUMERIC(12,2) NOT NULL,

    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE_APROBACION',
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_revision TIMESTAMPTZ,
    motivo_diferencia VARCHAR(500),
    motivo_rechazo VARCHAR(300),
    observaciones VARCHAR(500),

    CONSTRAINT fk_cierre_tanque
        FOREIGN KEY (tanque_id)
        REFERENCES tanque(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cierre_creado_por
        FOREIGN KEY (creado_por_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_cierre_revisado_por
        FOREIGN KEY (revisado_por_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_cierre_stock_inicial
        CHECK (stock_inicial >= 0),

    CONSTRAINT chk_cierre_totales
        CHECK (
            total_recepciones >= 0
            AND total_transferencias_entrada >= 0
            AND total_transferencias_salida >= 0
            AND total_despachos >= 0
            AND total_ajustes_positivos >= 0
            AND total_ajustes_negativos >= 0
        ),

    CONSTRAINT chk_cierre_stock_teorico
        CHECK (stock_teorico_final >= 0),

    CONSTRAINT chk_cierre_stock_fisico
        CHECK (stock_fisico_final >= 0),

    CONSTRAINT chk_cierre_estado
        CHECK (
            estado IN (
                'PENDIENTE_APROBACION',
                'APROBADO',
                'RECHAZADO'
            )
        ),

    CONSTRAINT chk_cierre_revision
        CHECK (
            estado = 'PENDIENTE_APROBACION'
            OR (
                revisado_por_usuario_id IS NOT NULL
                AND fecha_revision IS NOT NULL
            )
        ),

    CONSTRAINT chk_cierre_rechazo
        CHECK (
            estado <> 'RECHAZADO'
            OR motivo_rechazo IS NOT NULL
        )
);

 
-- 19. TABLA: notificacion
 

CREATE TABLE notificacion (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id UUID NOT NULL,
    tipo VARCHAR(40) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    mensaje VARCHAR(500) NOT NULL,
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_lectura TIMESTAMPTZ,

    CONSTRAINT fk_notificacion_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_notificacion_lectura
        CHECK (
            (leida = FALSE AND fecha_lectura IS NULL)
            OR
            (leida = TRUE AND fecha_lectura IS NOT NULL)
        )
);

 
-- 20. TABLA: audit_log
 

CREATE TABLE audit_log (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    usuario_id UUID,
    accion VARCHAR(50) NOT NULL,
    entidad VARCHAR(80) NOT NULL,
    entidad_id UUID,
    datos_anteriores JSONB,
    datos_nuevos JSONB,
    direccion_ip VARCHAR(45),
    user_agent VARCHAR(500),
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    hash_anterior VARCHAR(64),
    hash_actual VARCHAR(64) NOT NULL UNIQUE,

    CONSTRAINT fk_audit_log_usuario
        FOREIGN KEY (usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT
);

 
-- 21. TABLA: configuracion_sistema
 

CREATE TABLE configuracion_sistema (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(100) NOT NULL UNIQUE,
    valor TEXT NOT NULL,
    tipo_dato VARCHAR(20) NOT NULL,
    descripcion VARCHAR(250),
    editable BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    actualizado_por_usuario_id UUID,

    CONSTRAINT fk_configuracion_actualizado_por
        FOREIGN KEY (actualizado_por_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_configuracion_tipo_dato
        CHECK (
            tipo_dato IN (
                'STRING',
                'INTEGER',
                'DECIMAL',
                'BOOLEAN'
            )
        )
