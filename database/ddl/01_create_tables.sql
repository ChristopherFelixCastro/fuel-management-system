    cantidad_despachada NUMERIC(10,2) NOT NULL,
    odometro_registrado NUMERIC(12,2) NOT NULL,
    fecha_despacho TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    observaciones VARCHAR(500),
    direccion_ip VARCHAR(45),

    CONSTRAINT uq_despacho_ticket
        UNIQUE (ticket_id),

    CONSTRAINT fk_despacho_ticket
        FOREIGN KEY (ticket_id)
        REFERENCES ticket(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_despacho_usuario
        FOREIGN KEY (despachador_usuario_id)
        REFERENCES usuario(id)
        ON DELETE RESTRICT,

    CONSTRAINT fk_despacho_tanque
        FOREIGN KEY (tanque_id)
        REFERENCES tanque(id)
        ON DELETE RESTRICT,

    CONSTRAINT chk_despacho_cantidad
        CHECK (cantidad_despachada > 0),

    CONSTRAINT chk_despacho_odometro
        CHECK (odometro_registrado >= 0)
);


 
-- 14. TABLA: recepcion_combustible
 

CREATE TABLE recepcion_combustible (
